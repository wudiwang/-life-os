function defineLesson(day, title, goal, tip, words, dialogue) {
  const prefix = `d${String(day).padStart(2, '0')}`;
  return {
    day,
    title,
    goal,
    tip,
    words: words.map(([th, roman, zh], index) => ({ id: `${prefix}-w${index + 1}`, th, roman, zh })),
    dialogue: dialogue.map(([role, th, roman, zh], index) => ({ id: `${prefix}-l${index + 1}`, role, th, roman, zh })),
  };
}

