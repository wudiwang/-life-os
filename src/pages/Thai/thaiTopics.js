// 读音写法沿用 thaiLessons.js：à 低调、â 降调、á 高调、ǎ 升调，双写元音为长音。
// parts 写成 '读音=意思|读音=意思'，拼起来必须等于整句读音（thaiTopics.test.mjs 校验）。

const POLITE = '（礼貌尾词）'

function parseParts(text) {
  return text.split('|').map(chunk => {
    const [roman, meaning] = chunk.split('=')
    return { roman: roman.trim(), zh: (meaning || '').trim().replace(/^尾$/, POLITE) }
  })
}

function entry(id, th, zh, partsText, extra = {}) {
  const parts = parseParts(partsText)
  return { id, th, zh, roman: parts.map(p => p.roman).join(' '), parts, ...extra }
}

function scene(topic, key, icon, title, tip, words, patterns, dialogue) {
  const prefix = `${topic}-${key}`
  return {
    key, icon, title, tip,
    words: words.map(([th, zh, parts], i) => entry(`${prefix}-w${i + 1}`, th, zh, parts)),
    patterns: patterns.map(([frame, frameRoman, explain, th, zh, parts], i) => entry(`${prefix}-p${i + 1}`, th, zh, parts, { frame, frameRoman, explain })),
    dialogue: dialogue.map(([role, th, zh, parts], i) => entry(`${prefix}-l${i + 1}`, th, zh, parts, { role })),
  }
}

